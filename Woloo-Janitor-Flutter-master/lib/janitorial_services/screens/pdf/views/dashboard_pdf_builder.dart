  static pw.Widget _buildTableCell(
    String text, {
    bool isHeader = false,
    PdfColor? textColor,
  }) {
    return pw.Padding(
      padding: const pw.EdgeInsets.all(8),
      child: pw.Text(
        text,
        style: pw.TextStyle(
            fontSize: 12,
            fontWeight: isHeader ? pw.FontWeight.bold : pw.FontWeight.normal,
            color: textColor),
      ),
    );
  }

  static pw.Widget _buildTableCellWithBackground(
    String text, {
    PdfColor? backgroundColor,
    PdfColor? textColor,
  }) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(8),
      decoration: backgroundColor != null
          ? pw.BoxDecoration(color: backgroundColor)
          : null,
      child: pw.Text(
        text,
        style: pw.TextStyle(
          fontSize: 12,
          fontWeight: pw.FontWeight.normal,
          color: textColor ?? PdfColors.black,
        ),
      ),
    );
  }

  /// Get color for completion rate based on percentage ranges
  static Map<String, PdfColor> _getCompletionRateColor(double percentage) {
    if (percentage < 30) {
      // 0-30%: Red background, white text
      return {
        'bgColor': PdfColor.fromHex("#E1272E"),
        'textColor': PdfColors.white,
      };
    } else if (percentage < 60) {
      // 30-60%: Yellow background, black text
      return {
        'bgColor': PdfColor.fromHex("#FFEB00"),
        'textColor': PdfColors.black,
      };
    } else {
      // 60-100%: Green background, white text
      return {
        'bgColor': PdfColor.fromHex("#12B981"),
        'textColor': PdfColors.white,
      };
    }
  }

  static pw.TableRow _buildKpiRow(
    String metric,
    String value,
  ) {
    return pw.TableRow(
      children: [
        _buildTableCell(metric),
        _buildTableCell(value),
      ],
    );
  }

  static pw.TableRow _buildKpiRowColored(
    String metric,
    String value,
    PdfColor color,
  ) {
    return pw.TableRow(
      children: [
        pw.Padding(
          padding: const pw.EdgeInsets.all(8),
          child: pw.Row(
            children: [
              pw.SizedBox(width: 6),
              pw.Text(metric),
            ],
          ),
        ),
        _buildTableCell(value, textColor: color),
      ],
    );
  }

  static pw.Widget _buildStatusBadge(String status) {
    final PdfColor color = _getStatusColor(status);
    // Use black text for "completed" status, white for others
    final textColor =
        status.toLowerCase() == 'completed' ? PdfColors.black : PdfColors.white;

    return pw.Container(
      alignment: pw.Alignment.center,
      padding: const pw.EdgeInsets.all(8),
      decoration: pw.BoxDecoration(
        color: color,
      ),
      child: pw.Text(
        status,
        style: pw.TextStyle(
          color: textColor,
          fontSize: 10,
          fontWeight: pw.FontWeight.bold,
        ),
      ),
    );
  }

  static PdfColor _getStatusColor(String status) {
    switch (status.toLowerCase()) {
      // Task status colors
      case "completed":
        return PdfColor.fromHex("#C9F1FF");
      case "accepted":
        return PdfColor.fromHex("#8BDFFB");
      case "on going":
      case "ongoing":
        return PdfColor.fromHex("#33B8E4");
      case "requestforclosure":
      case "request for closure":
        return PdfColor.fromHex("#208AAC");
      case "pending":
        return PdfColor.fromHex("#19586C");
      case "rejected":
        return PdfColor.fromHex("#03171E");

      // Odor level status colors (existing)
      case "healthy":
        return PdfChartColors.good;
      case "moderate":
        return PdfChartColors.moderate;
      case "unhealthy":
        return PdfChartColors.critical;

      default:
        return PdfColors.grey;
    }
  }

  /// Get Tasks Completed from Task_status_distribution
  static String _getTasksCompleted(
