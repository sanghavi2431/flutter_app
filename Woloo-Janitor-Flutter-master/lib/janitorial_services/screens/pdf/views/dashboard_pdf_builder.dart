  /// Format DateTime to 12-hour format (e.g., "2:30 PM", "11:45 AM")
  static String _formatDateTimeTo12Hour(DateTime? dateTime) {
    if (dateTime == null) {
      return "N/A";
    }

    final hour = dateTime.hour;
    final minute = dateTime.minute;
    final period = hour >= 12 ? "PM" : "AM";
    final hour12 = hour == 0
        ? 12
        : hour > 12
            ? hour - 12
            : hour;
    final minuteStr = minute.toString().padLeft(2, '0');

    return "$hour12:$minuteStr $period";
  }

  /// Build janitor performance rows from Task_monitoring API data
  static List<pw.TableRow> _buildJanitorPerformanceRows(
      List<TaskMonitoring>? taskMonitoring) {
    if (taskMonitoring == null || taskMonitoring.isEmpty) {
      return [
        pw.TableRow(
          children: [
            _buildTableCell("No data available"),
            _buildTableCell(""),
            _buildTableCell(""),
          ],
        ),
      ];
    }

    // Group tasks by janitor name and calculate statistics
    final janitorStats = <String, Map<String, int>>{};

    for (var task in taskMonitoring) {
      if (task.janitorName != null && task.janitorName!.isNotEmpty) {
        final janitorName = task.janitorName!;

        // Initialize if not exists
        if (!janitorStats.containsKey(janitorName)) {
          janitorStats[janitorName] = {
            'assigned': 0,
            'completed': 0,
          };
        }

        // Count each TaskMonitoring entry as 1 assigned task (not based on taskNames.length)
        janitorStats[janitorName]!['assigned'] =
            (janitorStats[janitorName]!['assigned'] ?? 0) + 1;

        // Count as completed if status is "completed" (case-insensitive)
        // Each TaskMonitoring entry with completed status = 1 completed task
        if (task.status != null && task.status!.toLowerCase() == 'completed') {
          janitorStats[janitorName]!['completed'] =
              (janitorStats[janitorName]!['completed'] ?? 0) + 1;
        }
      }
    }

    if (janitorStats.isEmpty) {
      return [
        pw.TableRow(
          children: [
            _buildTableCell("No janitors available"),
            _buildTableCell(""),
            _buildTableCell(""),
          ],
        ),
      ];
    }

    // Convert to sorted list for consistent ordering
    final sortedJanitorNames = janitorStats.keys.toList()..sort();

    return sortedJanitorNames.map((janitorName) {
      final stats = janitorStats[janitorName]!;
      final assigned = stats['assigned'] ?? 0;
      final completed = stats['completed'] ?? 0;

      // Format: "completed/assigned"
      final tasksCompletedText = '$completed/$assigned';

      // Calculate completion rate percentage
      final completionRateValue =
          assigned > 0 ? (completed / assigned) * 100 : 0.0;
      final completionRate = completionRateValue.toStringAsFixed(1);
      final completionRateText = '$completionRate%';

      // Get color based on completion rate percentage
      final completionRateColor = _getCompletionRateColor(completionRateValue);

      return pw.TableRow(
        children: [
          _buildTableCell(janitorName),
          _buildTableCell(tasksCompletedText),
          _buildTableCellWithBackground(
            completionRateText,
            backgroundColor: completionRateColor['bgColor'] as PdfColor,
            textColor: completionRateColor['textColor'] as PdfColor,
          ),
        ],
      );
    }).toList();
  }
