  /// Get max value of avg_ppm_avg from avgppm_time_range array
  static String _getMaxAvgPpmAvg(DashboardData? dashboardData) {
    if (dashboardData?.results?.avgppmTimeRange == null ||
        dashboardData!.results!.avgppmTimeRange!.isEmpty) {
      return "0";
    }

    double maxValue = 0;
    for (var item in dashboardData.results!.avgppmTimeRange!) {
      final avgPpmAvg = double.tryParse(item.avgPpmAvg ?? "0") ?? 0;
      if (avgPpmAvg > maxValue) {
        maxValue = avgPpmAvg;
      }
    }

    return maxValue.toStringAsFixed(2);
  }

