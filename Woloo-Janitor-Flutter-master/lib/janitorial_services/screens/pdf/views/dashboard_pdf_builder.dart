  /// Get the "Changes from..." label based on selected range
  static String _getChangesLabel(String? selectedRange) {
    print("Selected Range: $selectedRange");
    if (selectedRange == null) {
      return "Changes from Yesterday";
    }

    switch (selectedRange) {
      case 'Today':
        return "Changes from Yesterday";
      case '7 days':
        return "Changes from last week";
      case 'Month':
        return "Changes from last month";
      default:
        return "Changes from Yesterday";
    }
  }

