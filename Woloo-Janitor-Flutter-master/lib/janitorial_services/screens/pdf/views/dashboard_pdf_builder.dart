  static Map<String, dynamic> _getChangesFromYesterdayAlertTrend(
      DashboardData? dashboardData) {
    final trend = dashboardData?.results?.todayVsYesterdayAlertTrend;

    if (trend == null) {
      return {
        'value': 'N/A',
        'color': PdfChartColors.blackText,
      };
    }

    final percentage = trend.percentageDifference;

    // Normalize to numeric value for comparison (percentageDifference can be String or num)
    double? numericValue;
    if (percentage is num) {
      numericValue = percentage.toDouble();
    } else if (percentage is String) {
      final cleaned = percentage.trim().toLowerCase();
      if (cleaned.replaceAll(' ', '') != 'nodata') {
        numericValue = double.tryParse(cleaned);
      }
    }

    final isPositive = (numericValue != null && numericValue >= 0);
    final arrow = isPositive ? '^' : 'v';
    final color = isPositive ? PdfChartColors.good : PdfChartColors.critical;

    String valueText = 'N/A';

    if (percentage != null) {
      // ✅ If it's a number (int or double)
      if (percentage is num) {
        final absPct = percentage.abs();
        valueText = '${absPct.toStringAsFixed(1)}%';
      }
      // ✅ If it's a String
      else if (percentage is String) {
        final cleaned = percentage.trim().toLowerCase();

        // Check for "no data" ignoring spaces & case
        if (cleaned.replaceAll(' ', '') == 'nodata') {
          valueText = 'No Comparison Data';
        } else {
          final parsed = double.tryParse(cleaned);
          if (parsed != null) {
            valueText = '${parsed.abs().toStringAsFixed(1)}%';
          } else {
            valueText = 'No Comparison Data';
          }
        }
      }
    }

    // If it's "No Comparison Data", don't show arrow
    if (valueText == 'No Comparison Data') {
      return {
        'value': valueText,
        'color': PdfChartColors.blackText,
      };
    }

    return {
      'value': '$arrow $valueText',
      'color': color,
    };
  }

