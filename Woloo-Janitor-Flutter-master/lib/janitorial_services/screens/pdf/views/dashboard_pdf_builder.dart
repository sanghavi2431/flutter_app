            _buildTableCell(""),
            _buildTableCell(""),
            _buildTableCell(""),
          ],
        ),
      ];
    }

    final rangeOfPpm = dashboardData.results?.rangeOfPpm;
    final healthyMax = double.tryParse(rangeOfPpm?.healthyMax ?? "0") ?? 0;
    final moderateMax = double.tryParse(rangeOfPpm?.moderateMax ?? "0") ?? 0;

    return dashboardData.results!.avgppmTimeRange!.map((item) {
      final timeRange = _convertTo12HourFormat(item.timeRange ?? "");
      final avgPpmAvg = item.avgPpmAvg ?? "0";
      final avgPcdMax = item.avgPcdMax ?? "0";
      final ppmValue = double.tryParse(avgPpmAvg) ?? 0;

      // Determine status based on ppm value and thresholds
      String status;
      if (ppmValue <= healthyMax) {
        status = "Healthy";
      } else if (ppmValue <= moderateMax) {
        status = "Moderate";
      } else {
        status = "Unhealthy";
      }

      return pw.TableRow(
        children: [
          _buildTableCell(timeRange),
          _buildTableCell(avgPpmAvg),
          _buildTableCell(avgPcdMax),
          _buildStatusBadge(status),
        ],
      );
    }).toList();
  }

  /// Convert 24-hour time range format (e.g., "0-3", "3-6") to 12-hour format (e.g., "12 AM - 3 AM", "3 AM - 6 AM")
  static String _convertTo12HourFormat(String timeRange) {
    try {
      // Parse time range like "0-3", "3-6", "6-9", etc.
      final parts = timeRange.split("-");
      if (parts.length != 2) {
        return timeRange; // Return original if format is unexpected
      }

      final startHour = int.tryParse(parts[0]) ?? 0;
      final endHour = int.tryParse(parts[1]) ?? 0;

      String formatHour(int hour) {
        if (hour == 0) {
          return "12 AM";
        } else if (hour < 12) {
          return "$hour AM";
        } else if (hour == 12) {
          return "12 PM";
        } else {
          return "${hour - 12} PM";
        }
      }

      return "${formatHour(startHour)} - ${formatHour(endHour)}";
    } catch (e) {
      return timeRange; // Return original if parsing fails
    }
  }

